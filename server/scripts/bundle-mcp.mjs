// Bundles the MCP server (+ SDK, zod, ISIC4 table) into one dependency-free
// file, mcp/sijilat-mcp.mjs, and packs it as a Claude Desktop extension,
// mcp/sijilat.mcpb. Installing is then "download + node <file>" or a double-click.
// Run via `npm run bundle:mcp`; commit both outputs so the raw GitHub URLs work.

import { build } from "esbuild";
import { readFileSync } from "node:fs";

const { version } = JSON.parse(readFileSync(new URL("../package.json", import.meta.url), "utf8"));

await build({
  entryPoints: ["src/mcp.ts"],
  outfile: "mcp/sijilat-mcp.mjs",
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node20",
  minify: true,
  legalComments: "none",
  banner: {
    js: [
      "#!/usr/bin/env node",
      `// sijilat-mcp ${version} — generated by scripts/bundle-mcp.mjs from src/; do not edit.`,
      // Some bundled CJS deps call require(); give ESM output a real one.
      'import { createRequire as __cr } from "node:module"; const require = __cr(import.meta.url);',
    ].join("\n"),
  },
  logLevel: "warning",
});
console.error("wrote mcp/sijilat-mcp.mjs");

// Claude Desktop extension: stage manifest (with this version) + bundle, pack.
import { cpSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { execFileSync } from "node:child_process";

const stage = mkdtempSync(join(tmpdir(), "sijilat-mcpb-"));
try {
  const manifest = JSON.parse(readFileSync("mcp/mcpb/manifest.json", "utf8"));
  writeFileSync(join(stage, "manifest.json"), JSON.stringify({ ...manifest, version }, null, 2));
  cpSync("mcp/sijilat-mcp.mjs", join(stage, "server/sijilat-mcp.mjs"));
  execFileSync("npx", ["-y", "@anthropic-ai/mcpb@2.1.2", "pack", stage, "mcp/sijilat.mcpb"], { stdio: "inherit" });
} finally {
  rmSync(stage, { recursive: true, force: true });
}

// Hashes for mcp/install.sh (PINNED_BUNDLE_SHA256 / PINNED_SKILL_SHA256). Paste
// them in, commit, then tag that commit as PINNED_REF (mcp-v<version>).
const { createHash } = await import("node:crypto");
const sha = (p) => createHash("sha256").update(readFileSync(p)).digest("hex");
console.error(`PINNED_REF=mcp-v${version}`);
console.error(`PINNED_BUNDLE_SHA256=${sha("mcp/sijilat-mcp.mjs")}`);
console.error(`PINNED_SKILL_SHA256=${sha("mcp/skill/sijilat/SKILL.md")}`);
